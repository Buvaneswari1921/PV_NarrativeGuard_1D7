"""
PV_NarrativeGuard - OAE Deterministic Decision Refinement

Purpose
-------
Refine the candidate deterministic OAE -> MedDRA inventory into
a controlled decision inventory.

IMPORTANT
---------
This script does NOT automatically declare terminology truth.

It separates candidate mappings into:

    SAFE_EXACT
    SAFE_ALIAS
    AMBIGUOUS
    NEEDS_REVIEW
    NOT_MAPPED

The original candidate inventory is never modified.
"""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path


# ============================================================
# PATHS
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parent

DATA_DIR = (
    PROJECT_ROOT
    / "meddra_rag"
    / "data"
)

INPUT_FILE = (
    DATA_DIR
    / "OAE_MedDRA_Deterministic_Candidate_Inventory.csv"
)

OUTPUT_FILE = (
    DATA_DIR
    / "OAE_MedDRA_Deterministic_Decision_Inventory.csv"
)

SUMMARY_FILE = (
    DATA_DIR
    / "OAE_MedDRA_Deterministic_Decision_Summary.csv"
)


# ============================================================
# HELPERS
# ============================================================

def clean(value) -> str:
    if value is None:
        return ""

    return str(value).strip()


def split_ids(value: str) -> list[str]:
    """
    Convert a candidate-ID field into unique MedDRA IDs.

    Handles common separators generated by the inventory builder.
    """

    value = clean(value)

    if not value:
        return []

    for separator in ("|", ";", ","):
        if separator in value:
            parts = value.split(separator)
            return sorted(
                {
                    part.strip()
                    for part in parts
                    if part.strip()
                }
            )

    return [value]


def unique_ids(*values: str) -> list[str]:
    result = set()

    for value in values:
        result.update(
            split_ids(value)
        )

    return sorted(result)


# ============================================================
# DECISION LOGIC
# ============================================================

def classify_row(row: dict) -> tuple[str, str]:
    """
    Determine the controlled decision category.

    Safety principle:
    - Never resolve multiple competing MedDRA candidates automatically.
    - A unique label-derived candidate is stronger than a
      synonym-derived candidate.
    """

    candidate_id = clean(
        row.get("candidate_meddra_id")
    )

    label_ids = unique_ids(
        row.get("label_candidate_ids", "")
    )

    synonym_ids = unique_ids(
        row.get("synonym_candidate_ids", "")
    )

    all_ids = unique_ids(
        candidate_id,
        row.get("label_candidate_ids", ""),
        row.get("synonym_candidate_ids", ""),
    )

    source_status = clean(
        row.get("deterministic_status")
    )

    review_required = clean(
        row.get("mapping_review_required")
    ).lower()

    # --------------------------------------------------------
    # No candidate
    # --------------------------------------------------------

    if not all_ids:
        return (
            "NOT_MAPPED",
            "No deterministic MedDRA candidate identified",
        )

    # --------------------------------------------------------
    # Multiple competing candidates
    # --------------------------------------------------------

    if len(all_ids) > 1:

        if (
            source_status == "AMBIGUOUS"
            or review_required == "true"
        ):
            return (
                "AMBIGUOUS",
                "Multiple MedDRA candidates require controlled resolution",
            )

        return (
            "NEEDS_REVIEW",
            "Multiple MedDRA candidates prevent deterministic acceptance",
        )

    # --------------------------------------------------------
    # Exactly one candidate
    # --------------------------------------------------------

    only_id = all_ids[0]

    # --------------------------------------------------------
    # Strongest case:
    # candidate comes directly from preferred label
    # --------------------------------------------------------

    if (
        len(label_ids) == 1
        and label_ids[0] == only_id
        and len(synonym_ids) <= 1
    ):
        return (
            "SAFE_EXACT",
            "Unique preferred-label MedDRA candidate",
        )

    # --------------------------------------------------------
    # Alias / synonym case
    # --------------------------------------------------------

    if (
        len(synonym_ids) == 1
        and synonym_ids[0] == only_id
    ):
        return (
            "SAFE_ALIAS",
            "Unique synonym-derived MedDRA candidate",
        )

    # --------------------------------------------------------
    # Existing SAFE candidate with one candidate overall
    # --------------------------------------------------------

    if (
        source_status == "SAFE"
        and len(all_ids) == 1
    ):
        return (
            "SAFE_EXACT",
            "Unique deterministic MedDRA candidate",
        )

    # --------------------------------------------------------
    # Conservative fallback
    # --------------------------------------------------------

    return (
        "NEEDS_REVIEW",
        "Candidate exists but deterministic acceptance is not sufficiently supported",
    )


# ============================================================
# MAIN
# ============================================================

def main() -> None:

    print("=" * 100)
    print(
        "PV NarrativeGuard - OAE Deterministic Decision Refinement"
    )
    print("=" * 100)

    if not INPUT_FILE.exists():

        raise FileNotFoundError(
            f"Input inventory not found:\n{INPUT_FILE}"
        )

    DATA_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    with INPUT_FILE.open(
        "r",
        encoding="utf-8-sig",
        newline="",
    ) as file:

        reader = csv.DictReader(file)

        rows = list(reader)

        fieldnames = list(
            reader.fieldnames or []
        )

    decisions = Counter()

    output_rows = []

    for row in rows:

        decision, reason = classify_row(
            row
        )

        row = dict(row)

        row[
            "controlled_decision"
        ] = decision

        row[
            "controlled_decision_reason"
        ] = reason

        output_rows.append(row)

        decisions[decision] += 1

    # --------------------------------------------------------
    # Write decision inventory
    # --------------------------------------------------------

    output_fieldnames = (
        fieldnames
        + [
            "controlled_decision",
            "controlled_decision_reason",
        ]
    )

    with OUTPUT_FILE.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=output_fieldnames,
        )

        writer.writeheader()

        writer.writerows(
            output_rows
        )

    # --------------------------------------------------------
    # Write summary
    # --------------------------------------------------------

    total = len(rows)

    summary_rows = []

    for decision in (
        "SAFE_EXACT",
        "SAFE_ALIAS",
        "AMBIGUOUS",
        "NEEDS_REVIEW",
        "NOT_MAPPED",
    ):

        count = decisions[decision]

        percentage = (
            (count / total) * 100
            if total
            else 0.0
        )

        summary_rows.append(
            {
                "controlled_decision": decision,
                "record_count": count,
                "percentage": round(
                    percentage,
                    2,
                ),
            }
        )

    with SUMMARY_FILE.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=[
                "controlled_decision",
                "record_count",
                "percentage",
            ],
        )

        writer.writeheader()

        writer.writerows(
            summary_rows
        )

    # --------------------------------------------------------
    # Console summary
    # --------------------------------------------------------

    print()
    print("-" * 100)
    print(
        "CONTROLLED DECISION SUMMARY"
    )
    print("-" * 100)

    print(
        f"Input records       : {total:,}"
    )

    for decision in (
        "SAFE_EXACT",
        "SAFE_ALIAS",
        "AMBIGUOUS",
        "NEEDS_REVIEW",
        "NOT_MAPPED",
    ):

        count = decisions[decision]

        percentage = (
            (count / total) * 100
            if total
            else 0.0
        )

        print(
            f"{decision:<18}: "
            f"{count:>6,} "
            f"({percentage:>6.2f}%)"
        )

    print()
    print(
        f"Decision inventory : {OUTPUT_FILE}"
    )

    print(
        f"Summary            : {SUMMARY_FILE}"
    )

    print()
    print(
        "IMPORTANT:"
    )
    print(
        "SAFE_EXACT and SAFE_ALIAS are controlled candidates,"
    )
    print(
        "not independent proof of MedDRA terminology truth."
    )
    print(
        "AMBIGUOUS and NEEDS_REVIEW remain gated."
    )

    print("=" * 100)


if __name__ == "__main__":
    main()