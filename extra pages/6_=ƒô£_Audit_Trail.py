# ============================================================
# HELPERS
# ============================================================

def clean_value(value) -> str:
    """
    Convert missing audit values into a clean UI representation.

    Empty / NaN values are shown as em dash rather than Python
    or pandas null representations.
    """

    if pd.isna(value):
        return "—"

    value = str(value).strip()

    if not value or value.lower() in {"nan", "none", "nat"}:
        return "—"

    return value


def prepare_audit_dataframe(audit_df: pd.DataFrame) -> pd.DataFrame:
    """
    Prepare audit data for presentation without modifying the
    persisted audit log.
    """

    if audit_df is None or audit_df.empty:
        return pd.DataFrame()

    df = audit_df.copy()

    # Ensure expected columns exist.
    for column in DISPLAY_COLUMNS:
        if column not in df.columns:
            df[column] = pd.NA

    # Parse timestamp for consistent display.
    if "audit_timestamp_utc" in df.columns:
        parsed = pd.to_datetime(
            df["audit_timestamp_utc"],
            errors="coerce",
            utc=True,
        )

        df["audit_timestamp_utc"] = parsed.dt.strftime(
            "%Y-%m-%d %H:%M:%S UTC"
        )

        df["audit_timestamp_utc"] = df[
            "audit_timestamp_utc"
        ].fillna("—")

    # Clean all visible values.
    for column in DISPLAY_COLUMNS:
        if column != "audit_timestamp_utc":
            df[column] = df[column].apply(clean_value)

    return df


def get_event_status(row: pd.Series) -> str:
    """
    Determine a simple UI classification for an audit event.
    """

    event_type = clean_value(row.get("event_type", ""))
    qc_status = clean_value(row.get("qc_status", ""))
    eligibility = clean_value(row.get("narrative_eligibility", ""))

    if qc_status == "PASS":
        return "COMPLETED"

    if "BLOCKED" in event_type:
        return "BLOCKED"

    if "FAILED" in event_type:
        return "FAILED"

    if "BLOCKED" in eligibility:
        return "BLOCKED"

    return "OTHER"


